#!/usr/bin/env python3
"""Cross-platform installer for Interviewly (macOS, Linux and Windows, Python 3.8+).

Antigravity: copies the native plugin bundle into place (or calls `agy plugin install`).
Claude Code and Codex: prints the host's own plugin commands, including Windows tips.

Usage:
    python3 install.py antigravity [--uninstall] [--dest DIR]
    python3 install.py claude
    python3 install.py codex
"""
import argparse
import json
import os
import shutil
import stat
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = "Im-yusuf/interviewly"
README_MARKER = "Generated by `scripts/build_antigravity.py`"


def is_interviewly(folder):
    """True when folder is an Antigravity build of Interviewly."""
    folder = Path(folder)
    try:
        data = json.loads((folder / "plugin.json").read_text(encoding="utf-8"))
        readme = (folder / "README.md").read_text(encoding="utf-8")
    except (OSError, ValueError):
        return False
    return isinstance(data, dict) and data.get("name") == "interviewly" and README_MARKER in readme


def _remove_readonly(func, path, exc_info):
    """Windows marks some files read-only, which rmtree can't delete: clear the flag and retry once."""
    if os.name != "nt":
        raise exc_info[1]
    os.chmod(path, stat.S_IWRITE)
    func(path)


def rmtree(path):
    """Delete an install. A linked one loses only its link, never the folder it points to."""
    path = Path(path)
    if path.is_symlink():
        path.unlink()
    else:
        shutil.rmtree(str(path), onerror=_remove_readonly)


def resolve_plugins_dir(dest=None):
    raw = dest or os.environ.get("ANTIGRAVITY_PLUGINS_DIR")
    if raw:
        return Path(os.path.expandvars(raw)).expanduser()
    return Path.home() / ".gemini" / "config" / "plugins"


def install_antigravity(dest=None, uninstall=False, bundle=None):
    bundle = Path(bundle) if bundle is not None else HERE / "dist" / "antigravity" / "interviewly"
    plugins_dir = resolve_plugins_dir(dest)
    target = plugins_dir / "interviewly"

    if uninstall:
        if not target.exists():
            print(f"Nothing installed at {target}")
            return 0
        if not is_interviewly(target):
            print(f"{target} exists and isn't an Interviewly install; not touching it.", file=sys.stderr)
            return 1
        try:
            rmtree(target)
        except OSError as exc:
            print(f"Couldn't remove {target}: {exc}", file=sys.stderr)
            return 1
        print(f"Removed {target}")
        print("Your saved data stays in ~/.interviewly until you delete it.")
        return 0

    if not is_interviewly(bundle):
        print(f"No built plugin at {bundle}. Run this script from a full clone: git clone https://github.com/{REPO}",
              file=sys.stderr)
        return 1

    agy = shutil.which("agy")
    if agy and not dest and not os.environ.get("ANTIGRAVITY_PLUGINS_DIR"):
        res = subprocess.run([agy, "plugin", "install", str(bundle)])
        if res.returncode != 0:
            return res.returncode
        print("Antigravity loads it automatically. Type: /interviewly:start")
        return 0

    if target.exists() and not is_interviewly(target):
        print(f"{target} exists and isn't an Interviewly install; not touching it.", file=sys.stderr)
        return 1

    # Stage beside the plugins directory: not in it, where Antigravity would load two copies during the swap, and
    # not in the system temp folder, where another disk turns each move into a copy that can fail halfway.
    plugins_dir.mkdir(parents=True, exist_ok=True)
    tmp = Path(tempfile.mkdtemp(prefix="interviewly-install-", dir=str(plugins_dir.parent)))
    try:
        staged = tmp / "interviewly"
        backup = tmp / "old"
        shutil.copytree(str(bundle), str(staged))
        had_old = target.exists() or target.is_symlink()
        try:
            if had_old:
                shutil.move(str(target), str(backup))
            shutil.move(str(staged), str(target))
        except OSError as exc:
            if had_old and backup.exists() and not target.exists():
                shutil.move(str(backup), str(target))
            print(f"Couldn't install to {target}: {exc}; nothing was changed.", file=sys.stderr)
            return 1
    finally:
        try:
            rmtree(tmp)
        except OSError:
            pass   # only our own staging folder is left behind

    print(f"Installed to {target}")
    print("Antigravity loads it automatically. Type: /interviewly:start")
    return 0


def print_claude():
    print("In Claude Code, run:")
    print(f"  /plugin marketplace add {REPO}")
    print("  /plugin install interviewly@interviewly")
    print("Then type: /interviewly:start")
    if sys.platform == "win32":
        print("Windows note: Claude Code uses Git for Windows; make sure Python 3.8+ is on PATH.")
    return 0


def print_codex():
    print("In a terminal, run:")
    print(f"  codex plugin marketplace add {REPO}")
    print("  codex plugin add interviewly@interviewly")
    print("Codex runs Interviewly's setup when you install it. Later, type: $interviewly:start")
    if sys.platform == "win32":
        print("Windows PowerShell note: type $interviewly:start inside Codex (or single-quote '$interviewly:start' in PowerShell).")
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(
        prog="install.py",
        description="Install Interviewly for Antigravity, or print install commands for Claude Code and Codex.",
    )
    parser.add_argument("platform", choices=("antigravity", "claude", "codex"))
    parser.add_argument("--uninstall", action="store_true", help="Remove an Antigravity install safely")
    parser.add_argument("--dest", help="Override Antigravity plugins directory (default: ~/.gemini/config/plugins)")
    args = parser.parse_args(argv)

    if args.platform == "antigravity":
        return install_antigravity(dest=args.dest, uninstall=args.uninstall)
    if args.platform == "claude":
        return print_claude()
    return print_codex()


if __name__ == "__main__":
    sys.exit(main())
