#!/usr/bin/env bash
# Install Interviewly. Antigravity: copies the native plugin into place.
# Claude Code and Codex install from their own plugin commands, shown below.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
repo="Im-yusuf/interviewly"

# True when folder $1 is an Antigravity build of Interviewly: its manifest is named "interviewly"
# and it has the README that scripts/build_antigravity.py writes.
is_interviewly() {
  python3 -c 'import json, sys
try:
    data = json.load(open(sys.argv[1], encoding="utf-8"))
except (OSError, ValueError):
    sys.exit(1)
sys.exit(not (isinstance(data, dict) and data.get("name") == "interviewly"))' "$1/plugin.json" \
    && grep -qF 'Generated by `scripts/build_antigravity.py`' "$1/README.md" 2>/dev/null
}

case "${1:-}" in
  antigravity)
    command -v python3 >/dev/null 2>&1 || { echo "Interviewly needs Python 3.8 or newer, and python3 wasn't found." >&2; exit 1; }
    plugins="${ANTIGRAVITY_PLUGINS_DIR:-$HOME/.gemini/config/plugins}"
    case "$plugins" in "~" | "~/"*) plugins="$HOME${plugins#\~}" ;; esac   # a quoted ~ isn't expanded
    dest="$plugins/interviewly"
    if [ "${2:-}" = "--uninstall" ]; then
      if [ ! -e "$dest" ]; then
        echo "Nothing installed at $dest"
        exit 0
      fi
      if ! is_interviewly "$dest"; then
        echo "$dest exists and isn't an Interviewly install; not touching it." >&2; exit 1
      fi
      rm -rf "$dest"
      echo "Removed $dest"
      echo "Your saved data stays in ~/.interviewly until you delete it."
      exit 0
    fi
    bundle="$here/dist/antigravity/interviewly"
    if ! is_interviewly "$bundle"; then
      echo "No built plugin at $bundle. Run this script from a full clone: git clone https://github.com/$repo" >&2; exit 1
    fi
    if command -v agy >/dev/null 2>&1 && [ -z "${ANTIGRAVITY_PLUGINS_DIR:-}" ]; then
      agy plugin install "$bundle"
    else
      if [ -e "$dest" ] && ! is_interviewly "$dest"; then
        echo "$dest exists and isn't an Interviewly install; not touching it." >&2; exit 1
      fi
      # Copy first, then swap, so a failed copy never leaves you without a working install.
      # The old copy goes to a folder beside the plugins folder: not in it, where it would load twice, and on the
      # same disk, so each move is a rename that can't stop halfway.
      mkdir -p "$plugins"
      tmp="$(mktemp -d "$(dirname "$plugins")/interviewly-install.XXXXXX")"
      trap 'rm -rf "$tmp"' EXIT
      cp -R "$bundle" "$tmp/interviewly"
      if [ -e "$dest" ]; then mv "$dest" "$tmp/old"; fi
      if ! mv "$tmp/interviewly" "$dest"; then
        if [ -e "$tmp/old" ]; then mv "$tmp/old" "$dest"; fi
        echo "Couldn't install to $dest; nothing was changed." >&2; exit 1
      fi
      echo "Installed to $dest"
    fi
    echo "Antigravity loads it automatically. Type: /interviewly:start"
    ;;
  claude)
    echo "In Claude Code, run:"
    echo "  /plugin marketplace add $repo"
    echo "  /plugin install interviewly@interviewly"
    echo "Then type: /interviewly:start"
    ;;
  codex)
    echo "In a terminal, run:"
    echo "  codex plugin marketplace add $repo"
    echo "  codex plugin add interviewly@interviewly"
    echo "Codex runs Interviewly's setup when you install it. Later, type: \$interviewly:start"
    ;;
  *)
    echo "Usage: ./install.sh antigravity [--uninstall] | claude | codex" >&2; exit 2
    ;;
esac
