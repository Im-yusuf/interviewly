#!/usr/bin/env python3
"""Build the native Antigravity plugin in dist/antigravity/interviewly from this repo.

The repo root is the Claude Code plugin (Codex reads it too). Antigravity needs its own
manifest and its own agent files, because agents name their tools differently there.
Everything else (skills, references, scripts) is shared and copied as it is.

Usage: python3 scripts/build_antigravity.py [OUT_DIR]
"""
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUT = ROOT / "dist" / "antigravity" / "interviewly"

# Claude Code tool name -> Antigravity tool names
TOOL_MAP = {
    "Read": ["view_file"],
    "Write": ["write_to_file"],
    "Edit": ["replace_file_content", "multi_replace_file_content"],
    "Glob": ["find_by_name", "list_dir"],
    "Grep": ["grep_search"],
    "Bash": ["run_command"],
}
SKILL_KEYS = ("name", "description")  # Antigravity reads these; Claude-only keys are dropped
SCRIPTS = tuple(sorted(p.name for p in (ROOT / "scripts").glob("*.py") if p.name != Path(__file__).name))  # all but this one


class BuildError(Exception):
    pass


def split_frontmatter(text):
    text = text.lstrip("\ufeff").replace("\r\n", "\n").replace("\r", "\n")   # a Windows (CRLF) checkout
    match = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not match:
        raise ValueError("missing frontmatter")
    return match.group(1), text[match.end():]


def frontmatter_fields(block):
    fields = {}
    for line in block.splitlines():
        key, sep, value = line.partition(":")
        if sep and not line.startswith((" ", "-")):
            fields[key.strip()] = value.strip()
    return fields


def convert_skill(text):
    block, body = split_frontmatter(text)
    fields = frontmatter_fields(block)
    head = "\n".join(f"{k}: {fields[k]}" for k in SKILL_KEYS if k in fields)
    return f"---\n{head}\n---\n{body}"


def convert_agent(text):
    block, body = split_frontmatter(text)
    fields = frontmatter_fields(block)
    tools = []
    for name in (t.strip() for t in fields.get("tools", "").split(",") if t.strip()):
        for mapped in TOOL_MAP.get(name, []):
            if mapped not in tools:
                tools.append(mapped)
    head = "\n".join([
        f"name: {fields['name']}",
        f"description: {fields['description']}",
        "tools:",
        *[f"  - {t}" for t in tools],
        "mainAgent: false",
        "subagent: true",
        "commandExecutionPolicy: auto",
    ])
    body = body.replace("~/.claude/plugins", "~/.gemini/config/plugins")
    return f"---\n{head}\n---\n{body}"


def manifest():
    claude = json.loads(read(ROOT / ".claude-plugin" / "plugin.json"))
    return {
        "$schema": "https://antigravity.google/schemas/v1/plugin.json",
        "name": claude["name"],
        "displayName": "Interviewly",
        "version": claude["version"],
        "description": claude["description"],
        "logo": "icon.png",
        "suggestedPrompts": [
            "Help me prepare for this job: <paste the job description>",
            "Quiz me on my project like a real interviewer",
            "What should I practise next?",
        ],
        "author": claude["author"],
        "homepage": claude["homepage"],
        "repository": claude["repository"],
        "license": claude["license"],
        "keywords": claude["keywords"],
    }


README = """# Interviewly for Antigravity

Generated by `scripts/build_antigravity.py` from the main repo. Don't edit these files here:
edit the repo and rebuild.

Install: run `./install.sh antigravity` from the repo root (or copy this folder to
`~/.gemini/config/plugins/interviewly` and restart Antigravity), then type `/interviewly:start`.

Full documentation: {homepage}
"""


def read(path):
    return Path(path).read_text(encoding="utf-8-sig")


def write(path, text):
    Path(path).write_text(text, encoding="utf-8")


def replaceable(out):
    """Only an earlier build is deleted: a missing or empty folder, or one whose plugin.json is Interviewly's."""
    out = Path(out).expanduser().resolve()
    if not out.exists():
        return True
    if not out.is_dir() or out == ROOT or out in ROOT.parents:
        return False
    if not any(out.iterdir()):
        return True
    try:
        return json.loads(read(out / "plugin.json")).get("name") == "interviewly"
    except (OSError, ValueError, AttributeError):
        return False


def build(out=DEFAULT_OUT):
    out = Path(out).expanduser().resolve()
    if not replaceable(out):
        raise BuildError(f"refusing to replace {out}: it isn't empty and isn't an earlier Interviewly build "
                         f"(no plugin.json named \"interviewly\"). Pass a new or empty folder.")
    if out.exists():
        shutil.rmtree(out)
    (out / "agents").mkdir(parents=True)
    for skill in sorted((ROOT / "skills").glob("*/SKILL.md")):
        target = out / "skills" / skill.parent.name / "SKILL.md"
        target.parent.mkdir(parents=True, exist_ok=True)
        write(target, convert_skill(read(skill)))
    for agent in sorted((ROOT / "agents").glob("*.md")):
        write(out / "agents" / agent.name, convert_agent(read(agent)))
    shutil.copytree(ROOT / "references", out / "references")
    (out / "scripts").mkdir()
    for name in SCRIPTS:
        shutil.copy2(ROOT / "scripts" / name, out / "scripts" / name)
    shutil.copy2(ROOT / ".claude-plugin" / "icon.png", out / "icon.png")
    shutil.copy2(ROOT / "LICENSE", out / "LICENSE")
    data = manifest()
    write(out / "plugin.json", json.dumps(data, indent=2) + "\n")
    write(out / "README.md", README.format(homepage=data["homepage"]))
    return out


if __name__ == "__main__":
    try:
        print(build(sys.argv[1] if len(sys.argv) > 1 else DEFAULT_OUT))
    except BuildError as e:
        sys.exit(str(e))
