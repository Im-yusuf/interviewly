#!/usr/bin/env python3
"""Build the native Antigravity plugin in dist/antigravity/interviewly from this repo.

The repo root is the Claude Code plugin (Codex reads it too). Antigravity needs its own
manifest and its own agent files, because agents name their tools differently there.
Everything else (skills, references, scripts) is shared and copied as it is.

Usage: python3 scripts/build_antigravity.py [OUT_DIR]
"""
import json
import re
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUT = ROOT / "dist" / "antigravity" / "interviewly"

# Claude Code tool name -> Antigravity tool names. A tool missing here fails the build, so an agent
# never ships to Antigravity without a tool it relies on.
TOOL_MAP = {
    "Read": ["view_file"],
    "Write": ["write_to_file"],
    "Edit": ["replace_file_content", "multi_replace_file_content"],
    "Glob": ["find_by_name", "list_dir"],
    "Grep": ["grep_search"],
    "Bash": ["run_command"],
}
SKILL_KEYS = ("name", "description")  # Antigravity reads these; Claude-only keys are dropped
README_MARKER = "Generated by `scripts/build_antigravity.py`"   # install.sh looks for it too
# The session reviewer's last fallback for finding the plugin names a Claude Code file; point it at Antigravity's.
CLAUDE_FALLBACK = re.compile(r"in Claude Code, the `installPath` of the `interviewly` entry in "
                             r"`~/\.claude/plugins/installed_plugins\.json`")
ANTIGRAVITY_FALLBACK = "in Antigravity, `~/.gemini/config/plugins/interviewly`"
SCRIPTS = tuple(sorted(p.name for p in (ROOT / "scripts").glob("*.py") if p.name != Path(__file__).name))  # all but this one


class BuildError(Exception):
    pass


def split_frontmatter(text, where="file"):
    text = text.lstrip("\ufeff").replace("\r\n", "\n").replace("\r", "\n")   # a Windows (CRLF) checkout
    match = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not match:
        raise BuildError(f"{where}: missing frontmatter")
    return match.group(1), text[match.end():]


def frontmatter_fields(block, where="file"):
    """The one-line `key: value` fields. A value written over several lines (a list, `>` or `|`)
    comes back as None, so a field the build keeps can't be silently emptied."""
    fields, key = {}, None
    for line in block.splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        if line.startswith((" ", "\t", "-")):
            if key is not None:
                fields[key] = None
            continue
        key, sep, value = line.partition(":")
        if not sep:
            raise BuildError(f"{where}: unreadable frontmatter line {line!r}")
        key, value = key.strip(), value.strip()
        fields[key] = None if value[:1] in ("", ">", "|") else value
    return fields


def required(fields, keys, where):
    for key in keys:
        if not fields.get(key):
            raise BuildError(f"{where}: `{key}` must be a value on one line (not empty, a list, `>` or `|`)")
    return [fields[key] for key in keys]


def yaml_problem(value):
    """Why a one-line value we copy into the bundle wouldn't read back as that string in YAML, or None."""
    if value.startswith('"'):
        try:
            return None if isinstance(json.loads(value), str) else "not a quoted string"
        except ValueError:
            return "an unfinished or invalid double-quoted string"
    if value.startswith("'"):
        whole = len(value) > 1 and value.endswith("'") and "'" not in value[1:-1].replace("''", "")
        return None if whole else "an unfinished single-quoted string"
    if value[0] in "[]{},&*!|>%@`#" or value.startswith(("- ", "? ", ": ")):
        return f"it starts with `{value[0]}`"
    if ": " in value or " #" in value or value.endswith(":"):
        return "it contains `: ` or ` #`"
    return None


def copied(fields, keys, where):
    """The values of keys written to the bundle as they are, each valid YAML on its own."""
    values = required(fields, keys, where)
    for key, value in zip(keys, values):
        problem = yaml_problem(value)
        if problem:
            raise BuildError(f"{where}: `{key}` isn't valid YAML ({problem}); reword it or put it in double quotes")
    return values


def convert_skill(text, where="SKILL.md"):
    block, body = split_frontmatter(text, where)
    values = copied(frontmatter_fields(block, where), SKILL_KEYS, where)
    head = "\n".join(f"{k}: {v}" for k, v in zip(SKILL_KEYS, values))
    return f"---\n{head}\n---\n{body}"


def convert_agent(text, where="agent"):
    block, body = split_frontmatter(text, where)
    fields = frontmatter_fields(block, where)
    name, description = copied(fields, ("name", "description"), where)
    tool_list, = required(fields, ("tools",), where)
    tools = []
    for tool in (t.strip() for t in tool_list.split(",")):
        if tool not in TOOL_MAP:
            raise BuildError(f"{where}: no Antigravity tool for `{tool}`; add one to TOOL_MAP")
        tools += [t for t in TOOL_MAP[tool] if t not in tools]
    # No commandExecutionPolicy: each agent follows the user's own terminal setting. The project analyst
    # reads repositories the user didn't necessarily write, so it must never run commands unasked.
    head = "\n".join([
        f"name: {name}",
        f"description: {description}",
        "tools:",
        *[f"  - {t}" for t in tools],
        "mainAgent: false",
        "subagent: true",
    ])
    body = CLAUDE_FALLBACK.sub(ANTIGRAVITY_FALLBACK, body)
    if "~/.claude" in body:
        raise BuildError(f"{where}: names a Claude Code path (~/.claude); give it an Antigravity equivalent "
                         f"in convert_agent")
    return f"---\n{head}\n---\n{body}"


def manifest():
    claude = json.loads(read(ROOT / ".claude-plugin" / "plugin.json"))
    return {
        "$schema": "https://antigravity.google/schemas/v1/plugin.json",
        "name": claude["name"],
        "displayName": "Interviewly",
        "version": claude["version"],
        "description": claude["description"],
        "logo": "icon.png",
        "suggestedPrompts": [
            "Help me prepare for this job: <paste the job description>",
            "Quiz me on my project like a real interviewer",
            "What should I practise next?",
        ],
        "author": claude["author"],
        "homepage": claude["homepage"],
        "repository": claude["repository"],
        "license": claude["license"],
        "keywords": claude["keywords"],
    }


def hooks_manifest():
    # Antigravity runs plugin hooks from the plugin root (sh -c on Unix, cmd /c on Windows).
    # `--format antigravity` writes the text to metadata.user_markdown with an empty systemMessage,
    # so the user sees the one-line reminder and the model never reads it.
    return {
        "interviewly-nudge": {
            "SessionStart": [
                {
                    "type": "command",
                    "command": (
                        "python3 scripts/interviewly.py nudge --format antigravity"
                        " || python scripts/interviewly.py nudge --format antigravity"
                        " || py -3 scripts/interviewly.py nudge --format antigravity"
                        " || echo {}"
                    ),
                    "timeout": 5,
                }
            ]
        }
    }


README = """# Interviewly for Antigravity

Generated by `scripts/build_antigravity.py` from the main repo. Don't edit these files here:
edit the repo and rebuild.

Install: run `./install.sh antigravity` from the repo root (or copy this folder to
`~/.gemini/config/plugins/interviewly`). Antigravity loads it automatically; type `/interviewly:start`.

Full documentation: {homepage}
"""


def read(path):
    return Path(path).read_text(encoding="utf-8-sig")


def write(path, text):
    Path(path).write_bytes(text.encode("utf-8"))   # "\n" on every OS: text mode would write "\r\n" on Windows


def replaceable(out):
    """Only an earlier build is replaced: a missing or empty folder, or one with the shape this script
    writes (an Antigravity plugin.json named interviewly, the generated README and a skills folder).
    Never the repo, a folder above it, the home folder, or a folder inside the repo other than dist/."""
    out = Path(out).expanduser().resolve()
    if out == ROOT or out in ROOT.parents or out == Path.home().resolve():
        return False
    if ROOT in out.parents and out != DEFAULT_OUT:
        return False
    if not out.exists():
        return True
    if not out.is_dir():
        return False
    if not any(out.iterdir()):
        return True
    try:
        data = json.loads(read(out / "plugin.json"))
        return (isinstance(data, dict) and data.get("name") == "interviewly"
                and str(data.get("$schema", "")).startswith("https://antigravity.google/")
                and README_MARKER in read(out / "README.md") and (out / "skills").is_dir())
    except (OSError, ValueError):
        return False


def write_bundle(out):
    (out / "agents").mkdir(parents=True)
    for skill in sorted((ROOT / "skills").glob("*/SKILL.md")):
        target = out / "skills" / skill.parent.name / "SKILL.md"
        target.parent.mkdir(parents=True, exist_ok=True)
        write(target, convert_skill(read(skill), f"skills/{skill.parent.name}/SKILL.md"))
    for agent in sorted((ROOT / "agents").glob("*.md")):
        write(out / "agents" / agent.name, convert_agent(read(agent), f"agents/{agent.name}"))
    shutil.copytree(ROOT / "references", out / "references",
                    ignore=shutil.ignore_patterns(".DS_Store", "__pycache__", "*.pyc"))
    (out / "scripts").mkdir()
    for name in SCRIPTS:
        shutil.copy2(ROOT / "scripts" / name, out / "scripts" / name)
    shutil.copy2(ROOT / ".claude-plugin" / "icon.png", out / "icon.png")
    shutil.copy2(ROOT / "LICENSE", out / "LICENSE")
    data = manifest()
    write(out / "plugin.json", json.dumps(data, indent=2) + "\n")
    write(out / "hooks.json", json.dumps(hooks_manifest(), indent=2) + "\n")
    write(out / "README.md", README.format(homepage=data["homepage"]))


def build(out=DEFAULT_OUT):
    """Build next to `out`, then swap it in, so a failed build leaves the previous one as it was."""
    out = Path(out).expanduser().resolve()
    if not replaceable(out):
        raise BuildError(f"refusing to replace {out}: it isn't empty and isn't an earlier Interviewly "
                         f"Antigravity build. Pass a new or empty folder outside the repo.")
    out.parent.mkdir(parents=True, exist_ok=True)
    stage = Path(tempfile.mkdtemp(prefix=".interviewly-build-", dir=out.parent))
    try:
        write_bundle(stage / "new")
        if out.exists():
            out.rename(stage / "old")
        try:
            (stage / "new").rename(out)
        except OSError:
            if (stage / "old").exists():
                (stage / "old").rename(out)
            raise
    finally:
        shutil.rmtree(stage, ignore_errors=True)
    return out


if __name__ == "__main__":
    try:
        print(build(sys.argv[1] if len(sys.argv) > 1 else DEFAULT_OUT))
    except BuildError as e:
        sys.exit(str(e))
